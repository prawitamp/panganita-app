/**
 * Helper untuk normalisasi nama kelas dari model YOLO ke data metadata Panganita
 */
export function getFoodMetadata(rawClass) {
  if (!rawClass) return null;
  const key = String(rawClass).toLowerCase().trim().replace(/\s+/g, "_");
  return FOOD_DETECTION_MAP[key] || null;
}
